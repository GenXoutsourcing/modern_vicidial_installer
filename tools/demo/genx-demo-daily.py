"""GenX multi-campaign demo data — backfill + daily refresh (campaign filtering / future multi-tenant).

Creates several demo campaigns (each a future "tenant": its own user_group, lists,
agents and lead pool) by CLONING the stock TESTCAMP row, then generates outbound
call history (vicidial_log + carrier/dial/agent/recording) per campaign per day.

Everything it writes is tagged so it is fully reversible and idempotent:
  - vicidial_log / vicidial_agent_log rows carry comments='DEMODAILY'
  - carrier_log / dial_log caller_code and every uniqueid start with 'MD'
  - recording_log.vicidial_id starts with 'MD'
A day is regenerated by DELETE-then-INSERT on those markers, so re-running any day
(or the hourly cron) never duplicates. DEMO6M (the 6-month TESTCAMP scale set) and
real traffic are left untouched.

Usage (emits SQL on stdout — pipe into mysql as root on the UI's DB, db1):
    genx-demo-daily.py --setup            | mysql -u root asterisk   # campaigns+lists+agents+leads only
    genx-demo-daily.py --backfill 35      | mysql -u root asterisk   # setup + last 35 days .. today
    genx-demo-daily.py --date 2026-07-18  | mysql -u root asterisk   # one specific day (no setup)
    genx-demo-daily.py                    | mysql -u root asterisk   # today only (cron default, no setup)

Deterministic per (campaign, day) via a seed derived from the date, so re-running a
day reproduces the same shape.
"""
