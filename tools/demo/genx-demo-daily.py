def emit_day(day, seq0):
    """One day of outbound data across every active campaign. Idempotent by markers."""
    today = date.today()
    now = datetime.now()
    wd = day.weekday()
    if wd == 6:                       # skip Sundays
        return seq0
    day_s = day.isoformat()
    nextday_s = (day + timedelta(days=1)).isoformat()
    base = int(time.mktime(day.timetuple()))
    day_compact = day_s.replace('-', '')
    is_today = day == today
    # deterministic shape per day
    random.seed(int(day_compact))
    rr, rnd = random.randrange, random.random

    # ---- idempotent wipe of this day's demo-daily footprint ----
    W(f"-- day {day_s}\n")
    W(f"DELETE FROM vicidial_log WHERE call_date>='{day_s} 00:00:00' AND call_date<'{nextday_s} 00:00:00' AND comments='DEMODAILY';\n")
    W(f"DELETE FROM vicidial_agent_log WHERE event_time>='{day_s} 00:00:00' AND event_time<'{nextday_s} 00:00:00' AND comments='DEMODAILY';\n")
    W(f"DELETE FROM vicidial_carrier_log WHERE call_date>='{day_s} 00:00:00' AND call_date<'{nextday_s} 00:00:00' AND caller_code LIKE 'MD%';\n")
    W(f"DELETE FROM vicidial_dial_log WHERE call_date>='{day_s} 00:00:00' AND call_date<'{nextday_s} 00:00:00' AND caller_code LIKE 'MD%';\n")
    W(f"DELETE FROM recording_log WHERE start_time>='{day_s} 00:00:00' AND start_time<'{nextday_s} 00:00:00' AND vicidial_id LIKE 'MD%';\n")

    vl = Tbl('vicidial_log', 'uniqueid,lead_id,list_id,campaign_id,call_date,start_epoch,end_epoch,length_in_sec,'
                             'status,phone_code,phone_number,user,comments,processed,user_group,term_reason,alt_dial,called_count')
    vcl = Tbl('vicidial_carrier_log', 'uniqueid,dialstatus,hangup_cause,channel,dial_time,answered_time,'
                                      'sip_hangup_cause,sip_hangup_reason,server_ip,call_date,lead_id,caller_code')
    vdl = Tbl('vicidial_dial_log', 'caller_code,lead_id,server_ip,call_date,extension,channel,context,timeout,'
                                   'outbound_cid,sip_hangup_cause,sip_hangup_reason,uniqueid')
    val = Tbl('vicidial_agent_log', 'user,server_ip,event_time,lead_id,campaign_id,pause_epoch,pause_sec,wait_epoch,'
                                    'wait_sec,talk_epoch,talk_sec,dispo_epoch,dispo_sec,status,user_group,comments,'
                                    'sub_status,dead_sec,uniqueid')
    rec = Tbl('recording_log', 'channel,server_ip,extension,start_time,start_epoch,end_time,end_epoch,length_in_sec,'
                               'length_in_min,filename,location,lead_id,user,vicidial_id')

    lo_s, hi_s = 9 * 3600, 18 * 3600
    if is_today and now.hour <= 18:
        hi_s = max(lo_s + 1800, now.hour * 3600 + now.minute * 60)
    seq = seq0
    for c in CAMPAIGNS:
        af = c.get('active_from')
        if af and day < af:
            continue
        agents = agent_ids(c)
        group = c['group']
        camp_lists = [lid for lid, _ in c['lists']] or None
        n_out = c['vol'] if wd < 5 else int(c['vol'] * 0.45)
        if is_today:
            if now.hour < 9:
                n_out = 0
            else:
                frac = min(1.0, ((now.hour - 9) * 60 + now.minute) / (9 * 60))
                n_out = int(n_out * frac)
        for _ in range(n_out):
            seq += 1
            sod = rr(lo_s, hi_s)
            sec = base + sod
            dt = f'{day_s} {sod // 3600:02d}:{(sod % 3600) // 60:02d}:{sod % 60:02d}'
            status, handled, lo, hi, dialstatus, cause, sip, reason, answered = OUT[rr(1000)]
            length = rr(lo, hi)
            if camp_lists:                       # tenant: lead from its own list pool
                list_id = camp_lists[seq % len(camp_lists)]
                llo, lhi = lead_range(list_id)
                lead = rr(llo, lhi)
            else:                                # TESTCAMP: reuse the 3M DEMO6M lead pool
                lead = rr(1_000_000, 4_000_000)
                list_id = 111 + lead % 12
            phone = 2_000_000_000 + lead
            uid = f'MD{sec}.{seq}'
            cc = f'MD{seq}'
            agent = agents[seq % len(agents)] if handled else 'VDAD'
            vl.add(f"('{uid}',{lead},{list_id},'{c['id']}','{dt}',{sec},{sec + length},{length},'{status}','1',"
                   f"'{phone}','{agent}','DEMODAILY','Y','{group}','{'AGENT' if handled else 'CALLER'}','MAIN',1)")
            vcl.add(f"('{uid}','{dialstatus}',{cause},'PJSIP/demo-{seq % 16777216:08x}',{rr(3, 28)},"
                    f"{length if answered else 0},{sip},'{reason}','{SIP}','{dt}',{lead},'{cc}')")
            vdl.add(f"('{cc}',{lead},'{SIP}','{dt}','91{phone}','Local/91{phone}@default','default','60',"
                    f"'\"DEMO\" <8005551234>',{sip},'{reason}','{uid}')")
            if handled:
                pause, wait, dispo = rr(0, 90), rr(3, 45), rr(8, 60)
                val.add(f"('{agent}','{SIP}','{dt}',{lead},'{c['id']}',{sec - wait - pause},{pause},{sec - wait},{wait},"
                        f"{sec},{length},{sec + length},{dispo},'{status}','{group}','DEMODAILY','',0,'{uid}')")
                if rnd() < 0.6:
                    fname = f"{c['id']}_{day_compact}-{sod // 3600:02d}{(sod % 3600) // 60:02d}{sod % 60:02d}_{agent}_{phone}"
                    loc = f'https://{HOST}/{AUDIO_DIR}/{AUDIO[seq % 5]}'
                    end_dt = f'{day_s} {(sod + length) // 3600:02d}:{((sod + length) % 3600) // 60:02d}:{(sod + length) % 60:02d}'
                    rec.add(f"('PJSIP/demo-{seq % 16777216:08x}','{SIP}','8309','{dt}',{sec},'{end_dt}',{sec + length},"
                            f"{length},'{length // 60}:{length % 60:02d}','{fname}','{loc}',{lead},'{agent}','{uid}')")
    for t in (vl, vcl, vdl, val, rec):
        t.flush()
    return seq


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--setup', action='store_true', help='emit campaigns/lists/agents/leads only')
    ap.add_argument('--backfill', type=int, metavar='DAYS', help='setup + generate the last DAYS days .. today')
    ap.add_argument('--date', metavar='YYYY-MM-DD', help='generate one specific day (no setup)')
    args = ap.parse_args()

    # NOTE: binlog is intentionally LEFT ON. db1 is the replication master for db2
    # (0s slave), so these writes must hit the binlog to reach db2. Run on db1 ONLY.
    W('SET SESSION bulk_insert_buffer_size=268435456;\n')

    if args.setup or args.backfill is not None:
        emit_setup(with_leads=True)
    if args.setup and args.backfill is None and not args.date:
        return

    today = date.today()
    if args.date:
        y, m, d = map(int, args.date.split('-'))
        days = [date(y, m, d)]
    elif args.backfill is not None:
        days = [today - timedelta(days=n) for n in range(args.backfill, -1, -1)]
    else:
        days = [today]                # cron default

    seq = 900_000_000
    for day in days:
        seq = emit_day(day, seq)
    sys.stderr.write(f'demo-daily: {len(days)} day(s), through seq {seq}\n')


if __name__ == '__main__':
    main()
